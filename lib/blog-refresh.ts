export function refreshBlogArticle(article: BlogArticle): BlogArticle {
  const patch = articlePatches[article.slug];
  if (!patch) return article;

  const sections = article.sections.map((section) => {
    const sectionPatch = patch.sections?.[section.id];
    return sectionPatch ? { ...section, ...sectionPatch } : section;
  });

  const sourceIndex = new Map(article.sources.map((source) => [source.url, source]));
  for (const source of patch.appendSources || []) sourceIndex.set(source.url, source);

  return {
    ...article,
    ...(patch.title ? { title: patch.title } : {}),
    ...(patch.description ? { description: patch.description } : {}),
    ...(patch.lead ? { lead: patch.lead } : {}),
    ...(patch.highlight ? { highlight: patch.highlight } : {}),
    ...(patch.readingTime ? { readingTime: patch.readingTime } : {}),
    updatedAt: '2026-09-19',
    sections,
    sources: Array.from(sourceIndex.values()),
  };
}
